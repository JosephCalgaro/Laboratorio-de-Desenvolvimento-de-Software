    public void preencherTabela(){
        FuncionarioDAO fdao = new FuncionarioDAO();
        List<Funcionario> listaFuncionarios = fdao.listar();
        
        DefaultTableModel tabela = (DefaultTableModel) tblFuncionarios.getModel();
        tabela.setNumRows(0);
        List<Funcionario> funcionariosExibidos = new ArrayList<>();
        
        if(listaFuncionarios == null){
            return;
        }
        
        for(Funcionario f : listaFuncionarios){
            funcionariosExibidos.add(f);
            Object[] obj = new Object[]{
              f.getId(),
              f.getNome(),
              f.getIdade(),
              f.getGenero(),
              f.getCargo(),
              f.getSalario()
            };
            tabela.addRow(obj);
        }
    }
    
