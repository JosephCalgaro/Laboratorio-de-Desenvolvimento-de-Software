    private void btnInserirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInserirActionPerformed
       Funcionario f = new Funcionario();
       String nome = txtNome.getText().trim();
       int idade = Integer.parseInt(txtIdade.getText().trim());
       double salario = Double.parseDouble(txtSalario.getText().trim().replace(",", "."));
       String genero = "";
       
       if(rbtnMasc.isSelected()){
           genero = "M";
       }else if(rbtnFem.isSelected()){
           genero = "F";
       }
       String cargo = cboxCargo.getSelectedItem().toString();
       
       
               
       f.setNome(nome);
       f.setIdade(idade);
       f.setSalario(salario);
       f.setGenero(genero);
       f.setCargo(cargo);
       
       FuncionarioDAO fdao = new FuncionarioDAO();
       fdao.inserir(f);
       JOptionPane.showMessageDialog(null, "Salvamento efetuado com sucesso", "Mensagem", JOptionPane.OK_OPTION);
       limparFormulario();
    }//GEN-LAST:event_btnInserirActionPerformed

