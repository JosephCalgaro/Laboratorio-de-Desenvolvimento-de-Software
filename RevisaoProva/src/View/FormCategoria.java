    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtCategoria.getText().trim();
        
        if(nome.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(
                this, "Informe o nome da categoria."
            );
            return;
        }
        
        Categoria categoria = new Categoria();
        categoria.setNome(nome);
        
        boolean sucesso = categoriaDAO.inserir(categoria);
        
        if(sucesso){
            javax.swing.JOptionPane.showMessageDialog(
                this, "Categoria cadastrada com sucesso!"
            );
            
            limparCampos();
            carregarCategorias();
        }else{
            javax.swing.JOptionPane.showMessageDialog(
                this, "Erro ao cadastrar categoria."
            );
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (idSelecionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Selecione uma categoria na tabela."
            );
            return;
        }

        String nome = txtCategoria.getText().trim();

        if (nome.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Informe o nome da categoria."
            );
            return;
        }

        Beans.Categoria categoria = new Beans.Categoria();

        categoria.setId(idSelecionado);
        categoria.setNome(nome);

        boolean sucesso = categoriaDAO.editar(categoria);

        if (sucesso) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Categoria atualizada com sucesso!"
            );

            limparCampos();
            carregarCategorias();

        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Erro ao atualizar categoria."
            );
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void tblCategoriaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCategoriaMouseClicked
        int linha = tblCategoria.getSelectedRow();

        if (linha < 0) {
            return;
        }

        
        idSelecionado = Integer.parseInt(
            tblCategoria.getValueAt(linha, 0).toString()
        );

       
        txtCategoria.setText(
            tblCategoria.getValueAt(linha, 1).toString()
        );
    }//GEN-LAST:event_tblCategoriaMouseClicked

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
         if (idSelecionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Selecione uma categoria na tabela."
            );
            return;
        }

        int resposta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir esta categoria?",
            "Confirmar exclusão",
            javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (resposta != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        boolean sucesso = categoriaDAO.excluir(idSelecionado);

        if (sucesso) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Categoria excluída com sucesso!"
            );

            limparCampos();
            carregarCategorias();
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao excluir categoria. Verifique se existem produtos vinculados."
            );
        }  
    }//GEN-LAST:event_btnExcluirActionPerformed

