    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Produto p = lerFormulario();
        if (p == null) {
            return; // validação já exibiu a mensagem de erro
        }
 
        produtoDAO.inserir(p);
        JOptionPane.showMessageDialog(this, "Produto salvo com sucesso!");
        limparFormulario();
        preencherTabela();
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
         if (idSelecionado == -1) {
            JOptionPane.showMessageDialog(this,
                    "Selecione um produto na tabela para editar.");
            return;
        }
 
        Produto p = lerFormulario();
        if (p == null) {
            return;
        }
        p.setId(idSelecionado);
 
        produtoDAO.editar(p);
        JOptionPane.showMessageDialog(this, "Produto atualizado com sucesso!");
        limparFormulario();
        preencherTabela();
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idSelecionado == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um produto na tabela para excluir.");
        return;
    }
    int resposta = JOptionPane.showConfirmDialog(this,
            "Deseja excluir o produto selecionado?",
            "Exclusão", JOptionPane.YES_NO_OPTION);
    if (resposta == JOptionPane.YES_OPTION) {
        produtoDAO.excluir(idSelecionado);
        limparFormulario();
        preencherTabela();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

