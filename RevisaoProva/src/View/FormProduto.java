    private void carregarCategorias() {
        DefaultComboBoxModel<Categoria> modelo = new DefaultComboBoxModel<>();
 
        for (Categoria categoria : categoriaDAO.listar()) {
            modelo.addElement(categoria);
        }
 
        cbCategoria.setModel(modelo);
    }
    
    public void preencherTabela() {
  
        String filtro = txtBuscar.getText().trim().toLowerCase();

        List<Produto> lista = produtoDAO.listar();

        DefaultTableModel tabela = (DefaultTableModel) tblProdutos.getModel();
        tabela.setNumRows(0);
        produtosExibidos = new java.util.ArrayList<>();

        if (lista == null) {
            return;
        }

        for (Produto p : lista) {
            if (!filtro.isEmpty() && !p.getNome().toLowerCase().contains(filtro)) {
                continue;
            }
            produtosExibidos.add(p);
            Object[] obj = new Object[]{
                p.getId(),
                p.getNome(),
                p.getPreco(),
                p.getQuantidade(),
                p.getNomeCategoria()
            };
            tabela.addRow(obj);
        }
    }
    
    private Produto lerFormulario() {
        String nome = txtNome.getText().trim();
        if (nome.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe o nome do produto.");
            txtNome.requestFocus();
            return null;
        }

        double preco;
        try {
            preco = Double.parseDouble(txtPreco.getText().trim().replace(",", "."));
            if (preco < 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Informe um preço válido (ex.: 19,90).");
            txtPreco.requestFocus();
            return null;
        }

        int quantidade;
        try {
            quantidade = Integer.parseInt(txtQuantidade.getText().trim());
            if (quantidade < 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Informe uma quantidade válida (número inteiro).");
            txtQuantidade.requestFocus();
            return null;
        }

        Categoria categoria = (Categoria) cbCategoria.getSelectedItem();
        if (categoria == null) {
            JOptionPane.showMessageDialog(this, "Selecione uma categoria.");
            return null;
        }

        Produto p = new Produto();
        p.setNome(nome);
        p.setPreco(preco);
        p.setQuantidade(quantidade);
        p.setCategoriaId(categoria.getId());
        return p;
    }
    
    private void limparFormulario() {
        idSelecionado = -1;
        txtNome.setText("");
        txtPreco.setText("");
        txtQuantidade.setText("");
        if (cbCategoria.getItemCount() > 0) {
            cbCategoria.setSelectedIndex(0);
        }
        tblProdutos.clearSelection();
        txtNome.requestFocus();
    }
      

