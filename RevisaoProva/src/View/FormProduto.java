    private void tblProdutosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProdutosMouseClicked
        int linha = tblProdutos.getSelectedRow();
        if (linha < 0) {
            return;
        }

        idSelecionado = (int) tblProdutos.getValueAt(linha, 0);
        txtNome.setText(tblProdutos.getValueAt(linha, 1).toString());
        txtPreco.setText(tblProdutos.getValueAt(linha, 2).toString());
        txtQuantidade.setText(tblProdutos.getValueAt(linha, 3).toString());

        Categoria categoriaProduto = (Categoria) tblProdutos.getValueAt(linha, 4);
        if (categoriaProduto != null) {
            for (int i = 0; i < cbCategoria.getItemCount(); i++) {
                Categoria c = (Categoria) cbCategoria.getItemAt(i);
                if (c.getId() == categoriaProduto.getId()) {
                    cbCategoria.setSelectedIndex(i);
                    break;
                }
            }
        }
    }//GEN-LAST:event_tblProdutosMouseClicked

