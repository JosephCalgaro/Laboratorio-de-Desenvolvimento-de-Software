    private void btnSalvarVeiculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarVeiculoActionPerformed
        Pessoa p = (Pessoa) cboxPessoa.getSelectedItem();
        Veiculo v = new Veiculo();
        v.setModelo(txtModelo.getText());
        v.setPlaca(txtPlaca.getText());
        v.setPessoaid(p);
        
        VeiculoDAO vDAO = new VeiculoDAO();
        vDAO.inserir(v);
        limparFormulario();
    }//GEN-LAST:event_btnSalvarVeiculoActionPerformed

    
    public void limparFormulario(){
        txtModelo.setText("");
        txtPlaca.setText("");
        cboxPessoa.setSelectedItem(0);
    }
    
    public void preencherComboPessoas(){
        PessoaDAO pDAO = new PessoaDAO();
        List<Pessoa> listaP = pDAO.getPessoa();
        for(Pessoa p : listaP){
            cboxPessoa.addItem(p);
        }
    }
