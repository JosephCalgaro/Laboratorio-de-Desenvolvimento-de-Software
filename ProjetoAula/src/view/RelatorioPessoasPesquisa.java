    public void preencherTabela(){
        String sexo = "";
        PessoaDAO pDAO = new PessoaDAO();
        
        if(rdbMasc.isSelected()){
            sexo = "M";
        }else if(rdbFem.isSelected()){
            sexo = "F";
        }else{
            sexo = "";
        }
        
        List<Pessoa> listaPessoas = pDAO.getPessoaNome(txtNomePesquisa.getText(), sexo);
        
        DefaultTableModel tabelaPessoas = (DefaultTableModel) tblPessoas.getModel();
        
        tabelaPessoas.setNumRows(0);
        
        for (Pessoa p : listaPessoas) {
            Object[] obj = new Object[]{
                p.getId(),
                p.getNome(),
                p.getSexo(),
                p.getIdioma()
            };
        
            tabelaPessoas.addRow(obj);
        }
    }

