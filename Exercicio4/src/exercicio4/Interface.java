    private void BtnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEditarActionPerformed
     if (indiceSelecionado == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Selecione um aluno na tabela."
        );
        return;
    }

    String sexo = "";

    if (CboxMasc.isSelected()) {
        sexo = "Masculino";
    } else if (CboxFem.isSelected()) {
        sexo = "Feminino";
    }

    Aluno aluno = listaAlunos.get(indiceSelecionado);

    aluno.setNome(TxtNome.getText());
    aluno.setDataNascimento(FtxtDataNasc.getText());
    aluno.setSexo(sexo);
    aluno.setMatricula(TxtMatricula.getText());
    aluno.setCurso(TxtCurso.getText());
    aluno.setCpf(FtxtCpf.getText());
    aluno.setEndereco(FtxtEndereco.getText());
    aluno.setTelefone(FtxtTelefone.getText());

    AlunoArquivo arquivo = new AlunoArquivo();
    arquivo.salvarTodos(listaAlunos);
    
    AtualizarTabela();

    JOptionPane.showMessageDialog(
        this,
        "Aluno editado com sucesso!"
    );
    
    
    }//GEN-LAST:event_BtnEditarActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        indiceSelecionado = jTable1.getSelectedRow();
        
        if (indiceSelecionado == -1) {
        return;
        }
        
         Aluno aluno = listaAlunos.get(indiceSelecionado);

        TxtNome.setText(aluno.getNome());
        FtxtDataNasc.setText(aluno.getDataNascimento());
        TxtMatricula.setText(aluno.getMatricula());
        TxtCurso.setText(aluno.getCurso());
        FtxtCpf.setText(aluno.getCpf());
        FtxtEndereco.setText(aluno.getEndereco());
        FtxtTelefone.setText(aluno.getTelefone());

        if (aluno.getSexo().equals("Masculino")) {
            CboxMasc.setSelected(true);
            CboxFem.setSelected(false);
        } else if (aluno.getSexo().equals("Feminino")) {
            CboxMasc.setSelected(false);
            CboxFem.setSelected(true);
        }

    }//GEN-LAST:event_jTable1MouseClicked

    private void BtnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnExcluirActionPerformed
            if (indiceSelecionado == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Selecione um aluno na tabela."
        );
        return;
        }

        listaAlunos.remove(indiceSelecionado);

        AlunoArquivo arquivo = new AlunoArquivo();
        arquivo.salvarTodos(listaAlunos);
        
        AtualizarTabela();

        LimparCampos();

        JOptionPane.showMessageDialog(
            this,
            "Aluno excluído com sucesso!"
        );
    }//GEN-LAST:event_BtnExcluirActionPerformed

