    private void AtualizarTabela(){
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);
        
        for(Aluno aluno : listaAlunos){
            modelo.addRow(new Object[]{
                aluno.getNome(),
                aluno.getMatricula(),
                aluno.getCurso(),
                aluno.getCpf(),
                aluno.getTelefone()
            });
        }
    }

