    private void BtnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnCadastrarActionPerformed
        String nome = TxtNome.getText();
        String dataNasc = FtxtDataNasc.getText();
        String curso = TxtCurso.getText();
        String cpf = FtxtCpf.getText();
        String endereco = FtxtEndereco.getText();
        String telefone = FtxtTelefone.getText();
        
        String matricula = TxtMatricula.getText();
        
        String sexo = "";
        
        if(CboxMasc.isSelected()){
            sexo = "Masculino";
        }else if(CboxFem.isSelected()){
            sexo = "Feminino";
        }
        
        Aluno aluno = new Aluno(
        nome,
        dataNasc,
        sexo,
        matricula,
        curso,
        cpf,
        endereco,
        telefone
    );
        
        AlunoArquivo arquivo = new AlunoArquivo();
        arquivo.salvar(aluno);
        
        listaAlunos.add(aluno);
        
        AtualizarTabela();
        LimparCampos();
           
    }//GEN-LAST:event_BtnCadastrarActionPerformed

